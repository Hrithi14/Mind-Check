package com.mindcheck.app.data.repository

import com.mindcheck.app.data.local.dao.WellnessReportDao
import com.mindcheck.app.data.local.entity.WellnessReportEntity
import kotlinx.coroutines.flow.Flow
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import kotlin.random.Random

class WellnessReportRepositoryImpl(
    private val dao: WellnessReportDao
) : WellnessReportRepository {

    override fun getAllReports(): Flow<List<WellnessReportEntity>> = dao.getAllReports()

    override suspend fun getReportById(id: Long): WellnessReportEntity? = dao.getReportById(id)

    override suspend fun saveReport(report: WellnessReportEntity): Long = dao.insertReport(report)

    override suspend fun deleteReport(id: Long) = dao.deleteReportById(id)

    override suspend fun generateInstantReport(): WellnessReportEntity {
        val dateFormat = SimpleDateFormat("MMM dd, yyyy", Locale.getDefault())
        val timeFormat = SimpleDateFormat("h:mm a", Locale.getDefault())
        val now = Date()
        val formattedDate = dateFormat.format(now)
        val formattedTime = timeFormat.format(now)

        val completionRate = Random.nextInt(75, 96)
        val tasksDone = Random.nextInt(18, 32)
        val avgScreenTime = Random.nextInt(38, 58)

        val calmVal = Random.nextInt(40, 55)
        val happyVal = Random.nextInt(25, 38)
        val stressedVal = Random.nextInt(10, 20)
        val tiredVal = (100 - calmVal - happyVal - stressedVal).coerceAtLeast(5)

        val insights = listOf(
            "Your highest focus streak was recorded on mid-week afternoons right after using Guided Breathing. Keeping study sessions to 25 minutes helped you complete $tasksDone goals!",
            "Morning stress levels reduced by 30% on days following 7+ hours of restful sleep. Digital wind-down routines directly bolstered next-day cognitive stamina.",
            "Consistent daily check-ins helped maintain calm equilibrium. Mid-day somatic micro-breaks sustained high focus through evening lectures."
        )

        val newReport = WellnessReportEntity(
            title = "Instant Wellness & Focus Report",
            dateRange = "Generated on $formattedDate · $formattedTime",
            categoryTag = "Mindfulness",
            secondaryBadge = "Instant Pulse",
            description = "Find calm and reset stress in just 5 mindful minutes a day. Recorded $completionRate% task completion with healthy usage.",
            taskCompletionRate = completionRate,
            tasksDoneCount = tasksDone,
            dailyAvgAppMinutes = avgScreenTime,
            appUsageCategory = "Healthy usage",
            moodCalmPercent = calmVal,
            moodHappyPercent = happyVal,
            moodStressedPercent = stressedVal,
            moodTiredPercent = tiredVal,
            bloomInsight = insights.random(),
            participantsCount = Random.nextInt(3500, 5000),
            authorTag = "BLOOM AI & Mind Check",
            createdAt = System.currentTimeMillis()
        )

        val id = dao.insertReport(newReport)
        return newReport.copy(id = id)
    }

    override fun formatReportForExport(report: WellnessReportEntity): String {
        return buildString {
            appendLine("========================================")
            appendLine("           MIND CHECK REPORT           ")
            appendLine("========================================")
            appendLine("Title: ${report.title}")
            appendLine("Date: ${report.dateRange}")
            appendLine("Category: ${report.categoryTag} | ${report.secondaryBadge}")
            appendLine("Generated by: ${report.authorTag}")
            appendLine("----------------------------------------")
            appendLine("METRICS OVERVIEW:")
            appendLine("  • Task Completion: ${report.taskCompletionRate}% (${report.tasksDoneCount} tasks completed)")
            appendLine("  • Daily Average App Time: ${report.dailyAvgAppMinutes}m (${report.appUsageCategory})")
            appendLine("----------------------------------------")
            appendLine("MOOD DISTRIBUTION (Past 7 Days):")
            appendLine("  • Calm / Peaceful:   ${report.moodCalmPercent}%")
            appendLine("  • Happy / Energized: ${report.moodHappyPercent}%")
            appendLine("  • Stressed / Rushed: ${report.moodStressedPercent}%")
            appendLine("  • Tired / Low Energy: ${report.moodTiredPercent}%")
            appendLine("----------------------------------------")
            appendLine("BLOOM INSIGHT:")
            appendLine("  \"${report.bloomInsight}\"")
            appendLine("========================================")
            appendLine("Notice: Mind Check is a non-clinical awareness tool.")
            appendLine("All health data remains encrypted on your physical device.")
        }
    }
}
